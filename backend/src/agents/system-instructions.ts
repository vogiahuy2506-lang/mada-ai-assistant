// Enhanced system instruction with structured context
export function getEnhancedSystemInstruction(
  language: string = 'vi',
  context?: {
    userIntent?: string;
    category?: string;
    urgency?: 'low' | 'medium' | 'high';
  }
): string {
  let instruction = getSystemInstruction(language);
  
  if (context?.userIntent) {
    const intentGuidance: Record<string, Record<string, string>> = {
      vi: {
        'product_inquiry': '\n[LƯU Ý: Người dùng đang hỏi về sản phẩm cụ thể - Ưu tiên liệt kê sản phẩm với thông số kỹ thuật]',
        'comparison': '\n[LƯU Ý: Người dùng muốn SO SÁNH - Tạo bảng so sánh rõ ràng]',
        'how_to': '\n[LƯU Ý: Người dùng cần hướng dẫn - Cung cấp steps chi tiết]',
        'recommendation': '\n[LƯU Ý: Người dùng cần tư vấn - Đề xuất giải pháp tối ưu]',
        'troubleshooting': '\n[LƯU Ý: Người dùng gặp vấn đề - Giúp debug/tìm nguyên nhân]',
      },
      en: {
        'product_inquiry': '\n[NOTE: User is asking about specific products - Prioritize listing with specifications]',
        'comparison': '\n[NOTE: User wants to COMPARE - Create clear comparison table]',
        'how_to': '\n[NOTE: User needs guidance - Provide detailed steps]',
        'recommendation': '\n[NOTE: User needs consultation - Recommend optimal solution]',
        'troubleshooting': '\n[NOTE: User has issues - Help debug/find causes]',
      },
    };
    
    const guidance = intentGuidance[language]?.[context.userIntent] || '';
    instruction += guidance;
  }
  
  return instruction;
}

